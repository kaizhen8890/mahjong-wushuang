import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { relativeSeat, ownHand, meldDisplay, choiceTiles, distinctCalls } from '../lib/virtual-mahjong/table-view';
import { createTiles, tileCode } from '../lib/virtual-mahjong/tiles';
import { MahjongMatchEngine } from '../lib/virtual-mahjong/match-engine';
import { defaultRules } from '../lib/virtual-mahjong/rules';

for (let own = 0; own < 4; own++) assert.deepEqual(Array.from({ length: 4 }, (_, i) => relativeSeat((own + i) % 4, own, 4)), [0, 1, 2, 3]);
assert.deepEqual([0, 1, 2].map(seat => relativeSeat(seat, 0, 3)), [0, 1, 3]);
const tiles = createTiles(4, true);
const sample = [{ id: 1, type: 2, red: false }, { id: 2, type: 1, red: false }, { id: 3, type: 3, red: false }];
assert.deepEqual(choiceTiles(sample, [3, 2], sample[0]).map(tile => tile.type), [1, 2, 3]);
assert.deepEqual(sample.map(tile => tile.id), [1, 2, 3]);
const fives = [{ id: 1, type: 4, red: false }, { id: 2, type: 4, red: false }, { id: 3, type: 4, red: false }, { id: 4, type: 4, red: true }];
const options = [[1, 2], [2, 3], [1, 3], [1, 4], [2, 4]].map((consumeTileIds, i) => ({ id: `pon-${i}`, kind: 'pon' as const, consumeTileIds }));
assert.deepEqual(distinctCalls(options, fives).map(option => option.id), ['pon-0', 'pon-3']);
assert.equal(options.length, 5);
for (const tile of tiles) assert.ok(existsSync(`public/virtual-tiles/${tileCode(tile)}.svg`));
assert.ok(existsSync('public/virtual-tiles/back.svg'));
const seats = ['a', 'b', 'c', 'd'].map((id, seat) => ({ id, seat }));
const meld = { id: 'm', kind: 'kakan' as const, tiles: tiles.slice(0, 4), sourcePlayerId: 'd', calledTileId: 0, addedTileId: 3 };
const display = meldDisplay(meld, 0, seats);
assert.equal(display[0].tile.id, 0); assert.equal(display[1].added, true);
assert.equal(display.filter(item => item.sideways).length, 2);
const ankan = meldDisplay({ ...meld, kind: 'ankan', sourcePlayerId: null, calledTileId: null, addedTileId: null }, 0, seats);
assert.deepEqual(ankan.map(item => item.back), [true, false, false, true]);
const engine = new MahjongMatchEngine({ gameId: 'ui', rules: defaultRules(), dealerSeat: 0, players: seats.map(item => ({ id: item.id, name: item.id })) }, { now: () => 0, random: () => 12345 });
const view = engine.view({ role: 'player', playerId: 'a' });
const before = structuredClone(view);
assert.equal(ownHand(view).at(-1)!.id, view.players[0].drawnTileId);
assert.deepEqual(view, before);
assert.equal(ownHand(engine.view({ role: 'spectator' })).length, 0);
console.log('Virtual table display: seat orientation, tile assets, kan display, drawn-tile separation and projection isolation passed.');
