import assert from 'node:assert/strict';
import { VirtualRoomHost, VIRTUAL_ROOM_PROTOCOL } from '../lib/virtual-mahjong/room';
import { VirtualRoomClient } from '../lib/virtual-mahjong/room-client';
import { defaultRules } from '../lib/virtual-mahjong/rules';
import { saveRoom, loadRoom, clearRoom, VIRTUAL_SAVE_KEY } from '../lib/virtual-mahjong/room-storage';
let now = 1000, id = 0;
let room = new VirtualRoomHost({ roomId: 'r', code: 'ABC123', hostName: 'Host', rules: defaultRules(3) }, { now: () => now, random: () => 123 }, () => `id-${++id}`);
const wire = (connection: string, data: object) => room.receive(connection, JSON.stringify({ protocol: VIRTUAL_ROOM_PROTOCOL, roomId: 'r', ...data })).map(item => ({ connectionId: item.connectionId, ...JSON.parse(item.text) }));
const a = wire('old-a', { type: 'JOIN', code: 'ABC123', name: 'A' })[0];
wire('old-b', { type: 'JOIN', code: 'ABC123', name: 'B' });
room.setHostReady(true);
for (const peer of ['old-a', 'old-b']) wire(peer, { type: 'READY', ready: true, configurationRevision: room.localView().configurationRevision });
const waiting = room.exportCheckpoint();
const lobby = VirtualRoomHost.restoreCheckpoint(waiting, { now: () => 900000 });
assert.ok(lobby.localView().seats.every(seat => !seat.ready));
assert.equal(lobby.localView().seats.filter(seat => seat.connected).length, 1);
assert.throws(() => lobby.start(), /NOT_READY/);
room.start(); now += 500;
const before = room.localView();
const saved = room.exportCheckpoint();
now = 900000;
room = VirtualRoomHost.restoreCheckpoint(JSON.parse(JSON.stringify(saved)), { now: () => now, random: () => { throw new Error('Restore must not reshuffle'); } });
const after = room.localView();
assert.equal(after.serverNow, saved.savedAt);
assert.deepEqual(after.game!.players.map(player => player.hand), before.game!.players.map(player => player.hand));
assert.deepEqual(after.game!.availableActions, before.game!.availableActions);
assert.equal(after.game!.roundId, before.game!.roundId);
assert.ok(after.revision > before.revision);
assert.equal(wire('old-a', { type: 'SNAPSHOT_REQUEST' })[0].error, 'NOT_AUTHENTICATED');
assert.equal(wire('bad', { type: 'RECONNECT', playerId: a.playerId, reconnectToken: 'wrong' })[0].error, 'AUTH_FAILED');
const storageData = new Map<string, string>(); storageData.set('physical-game', 'unchanged');
const storage = { getItem: (key: string) => storageData.get(key) ?? null, setItem: (key: string, value: string) => { storageData.set(key, value); }, removeItem: (key: string) => { storageData.delete(key); } };
saveRoom(storage, { format: 'musou.local.room', version: 1, role: 'host', checkpoint: saved });
assert.equal(loadRoom(storage)?.role, 'host');
saveRoom(storage, { format: 'musou.local.room', version: 1, role: 'client', name: 'A', host: '192.168.1.2', port: 8765, code: 'ABC123', credentials: { roomId: 'r', playerId: a.playerId, reconnectToken: a.reconnectToken } });
const clientSave = loadRoom(storage)!; assert.equal(clientSave.role, 'client');
if (clientSave.role !== 'client') throw new Error();
assert.doesNotMatch(storage.getItem(VIRTUAL_SAVE_KEY)!, /wall|hand|checkpoint/);
const client = new VirtualRoomClient(clientSave.name, clientSave.code, clientSave.credentials);
let outgoing = [client.connected()];
while (outgoing.length) outgoing = outgoing.flatMap(text => room.receive('new-a', text).filter(item => item.connectionId === 'new-a').flatMap(item => client.receive(item.text)));
assert.ok(client.active); assert.equal(client.view()!.game!.viewerId, a.playerId);
assert.equal(client.view()!.game!.players.filter(player => player.hand).length, 1);
assert.equal(room.localView().seats[1].connected, true);
assert.equal(room.localView().seats[2].connected, false);
now += 250; assert.equal(room.localView().serverNow, saved.savedAt + 250);
const again = room.exportCheckpoint(); assert.equal(again.savedAt, saved.savedAt + 250);
VirtualRoomHost.restoreCheckpoint(again, { now: () => now + 100000 });
for (const mutate of [(value: typeof saved) => { value.seats[1].id = value.seats[0].id; }, (value: typeof saved) => { value.seats[1].token = value.seats[0].token; }, (value: typeof saved) => { value.hostPlayerId = 'missing'; }, (value: typeof saved) => { value.options.rules.redFives = !value.options.rules.redFives; }]) {
  const bad = structuredClone(saved); mutate(bad); assert.throws(() => VirtualRoomHost.restoreCheckpoint(bad, { now: () => now }), /INVALID_ROOM_CHECKPOINT/);
}
storage.setItem(VIRTUAL_SAVE_KEY, '{broken'); assert.throws(() => loadRoom(storage), /无法读取/);
assert.throws(() => saveRoom({ ...storage, setItem: () => { throw new Error('quota'); } }, clientSave), /quota/);
clearRoom(storage); assert.equal(loadRoom(storage), null); assert.equal(storageData.get('physical-game'), 'unchanged');
console.log('PASS room recovery: Host restart without shuffle, logical clock, offline seats, credential reconnect, private storage, malformed saves and quota errors');
