import assert from 'node:assert/strict';
import { createGameState } from '../lib/mahjong';
import { recordRiichiTransitions } from '../lib/presentation';
import { applyRemoteControllerCommand } from '../lib/remote-command';
import { createControllerSnapshot } from '../lib/controller-snapshot';
import { parseServerMessage, serializeWireMessage } from '../lib/lan-protocol';
const game = createGameState();
const winner = game.players[0], loser = game.players[1];
const riichi = recordRiichiTransitions(game, { ...game, players: game.players.map(p => ({ ...p, riichi: p.id === winner.id })) });
assert.equal(riichi.presentations?.length, 1);
assert.equal(recordRiichiTransitions(riichi, riichi).presentations?.length, 1);
const draft = { winType: 'ron' as const, loserPlayerId: loser.id, tiles: [], closed: true, fu: 30,
  selectedYakuIds: ['riichi'], yakuOverrides: {}, dora: 4, uraDora: 0, akaDora: 0, flowerDora: 0, bonusHan: 0, extraPoints: 0 };
const win = applyRemoteControllerCommand(game, [], winner.id, { kind: 'win.commit', draft }).nextGame;
const event = win.presentations![0];
assert.equal(event.kind, 'win'); assert.equal(event.winType, 'ron'); assert.equal(event.loserId, loser.id);
assert.equal(event.han, 5); assert.match(event.limit, /满贯/); assert.equal(event.tiles.length, 0);
assert.equal(event.scores[0].after, win.players[0].score);
assert.equal(event.scores[1].before, loser.score);
const snapshot = createControllerSnapshot(win, [], { roomId:'room', matchId:'match', handId:'hand', revision:2, playerId:loser.id });
assert.equal(snapshot.presentations![0].scores.length, 1);
assert.equal(snapshot.presentations![0].scores[0].playerId, loser.id);
const decoded = parseServerMessage(serializeWireMessage({protocol: 5,type:'state.snapshot',sentAt:Date.now(),roomId:'room',snapshot}));
assert.equal(decoded.ok, true, JSON.stringify(decoded));
if(decoded.ok && decoded.value.type === 'state.snapshot') assert.deepEqual(decoded.value.snapshot.presentations, snapshot.presentations);
const tsumo = applyRemoteControllerCommand(game, [], winner.id, {kind:'win.commit', draft:{...draft, winType:'tsumo', loserPlayerId:undefined}}).nextGame.presentations![0];
assert.equal(tsumo.winType,'tsumo'); assert.equal(tsumo.loserId,undefined);
assert.equal(tsumo.scores.filter(s=>s.before!==s.after).length,4);
assert.equal(createControllerSnapshot({...win,presentations:[{...event,createdAt:Date.now()-30000}]},[],{roomId:'r',matchId:'m',handId:'h',revision:1,playerId:winner.id}).presentations?.length,0);
console.log('Presentation state, public snapshot privacy, protocol roundtrip, ron/tsumo and stale filtering passed.');
